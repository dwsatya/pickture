import { NextRequest, NextResponse } from 'next/server';
import { getDrive } from '@/lib/google-drive';
import { getAdminClient } from '@/lib/supabase/server';

export const instant = false;

const ALLOWED_SIZES = ['400', '600', '1600'] as const;
type AllowedSize = (typeof ALLOWED_SIZES)[number];

export async function GET(
  request: NextRequest,
  { params }: { params: Promise<{ fileId: string }> }
) {
  const { fileId } = await params;
  const searchParams = request.nextUrl.searchParams;
  const rawSize = searchParams.get('size') || '600';
  const size: AllowedSize = ALLOWED_SIZES.includes(rawSize as AllowedSize)
    ? (rawSize as AllowedSize)
    : '600';

  if (!fileId) {
    return new NextResponse('File ID required', { status: 400 });
  }

  // 1. Validate that fileId belongs to an active, non-closed session in Supabase
  try {
    const supabase = getAdminClient();
    const { data: photo, error: photoErr } = await supabase
      .from('photos')
      .select('id, drive_file_id, sessions:sessions!photos_session_id_fkey(status, expires_at)')
      .eq('drive_file_id', fileId)
      .single();

    if (photoErr || !photo) {
      return new NextResponse('Photo not found', { status: 404 });
    }

    const session = Array.isArray(photo.sessions) ? photo.sessions[0] : photo.sessions;
    if (session) {
      if (session.status === 'closed') {
        return new NextResponse('Session closed', { status: 403 });
      }
      if (session.expires_at && new Date(session.expires_at) < new Date()) {
        return new NextResponse('Session expired', { status: 403 });
      }
    }
  } catch (dbErr) {
    console.error('Error validating photo in DB:', dbErr);
    // Proceed if DB check has a temporary glitch, but log
  }

  // 2. Fetch thumbnail link from Google Drive API
  try {
    const drive = getDrive();
    const fileRes = await drive.files.get({
      fileId,
      fields: 'thumbnailLink',
      supportsAllDrives: true,
    });

    const rawThumb = fileRes.data.thumbnailLink;

    if (rawThumb) {
      // Replace size suffix =s220 with requested size =s400, =s600, =s1600
      const resizedThumbUrl = rawThumb.replace(/=s\d+(-[a-z]+)?$/, `=s${size}`);

      const imgRes = await fetch(resizedThumbUrl);
      if (imgRes.ok) {
        const imageBuffer = await imgRes.arrayBuffer();

        return new NextResponse(imageBuffer, {
          headers: {
            'Content-Type': imgRes.headers.get('content-type') || 'image/jpeg',
            'Cache-Control': 'public, max-age=31536000, s-maxage=31536000, immutable',
          },
        });
      }
    }

    // Fallback if thumbnail is not yet generated by Drive: stream media directly
    const mediaRes = await drive.files.get(
      {
        fileId,
        alt: 'media',
        supportsAllDrives: true,
      },
      { responseType: 'stream' }
    );

    // Convert node stream to web stream
    const stream = mediaRes.data as unknown as ReadableStream;
    return new NextResponse(stream, {
      headers: {
        'Content-Type': 'image/jpeg',
        'Cache-Control': 'public, max-age=86400',
      },
    });
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : String(err);
    console.error('Error proxying image from Drive:', msg);

    // Return friendly placeholder SVG if photo cannot be loaded
    const placeholderSvg = `
      <svg width="${size}" height="${Math.round(Number(size) * 1.5)}" xmlns="http://www.w3.org/2000/svg">
        <rect width="100%" height="100%" fill="#f4f4f5"/>
        <text x="50%" y="50%" dominant-baseline="middle" text-anchor="middle" font-family="sans-serif" font-size="14" fill="#71717a">
          Memproses foto...
        </text>
      </svg>
    `.trim();

    return new NextResponse(placeholderSvg, {
      headers: {
        'Content-Type': 'image/svg+xml',
        'Cache-Control': 'public, max-age=60',
      },
    });
  }
}
